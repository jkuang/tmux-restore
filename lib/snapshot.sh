# Snapshot capture and publication. Called while holding snapshot.lock.

tr_snapshot_metadata() {
    local d=$TR_FIELD end=$TR_ROW stage=$1
    tr_tmux list-sessions -F "#{session_id}${d}#{session_name}${d}#{window_index}${end}" > "$stage/sessions" &&
    tr_tmux list-windows -a -F "#{session_id}${d}#{window_id}${d}#{window_index}${d}#{window_zoomed_flag}${d}#{window_width}${d}#{window_height}${d}#{window_name}${d}#{window_layout}${end}" > "$stage/windows" &&
    tr_tmux list-panes -a -F "#{window_id}${d}#{pane_id}${d}#{pane_index}${d}#{pane_output_generation}:#{history_generation}:#{history_size}:#{history_added}:#{history_collected}:#{pane_width}:#{pane_height}${d}#{pane_current_path}${d}#{pane_current_command}${d}#{?pane_dead,,#{pane_pid}}${end}" > "$stage/panes.meta"
}

tr_save_panes() {
    local stage=$1 previous=$2 row pane key signature record_dir path old_signature
    local captured=0 reused=0
    while IFS= read -r -d "$TR_ROW" row; do
        tr_fields "$row" 7 && tr_window_id "${TR_FIELDS[0]}" && tr_pane_id "${TR_FIELDS[1]}" &&
            tr_uint "${TR_FIELDS[2]}" || { tr_error 'Invalid pane metadata.'; return 1; }
        pane=${TR_FIELDS[1]}
        key=${pane#%}
        signature=$TR_SERVER:${TR_FIELDS[3]}
        path=$stage/panes/$key
        [[ -f $path.screen ]] && continue # A linked window can be listed twice.

        record_dir=$(tr_record_dir "$pane")
        if [[ -r $record_dir/pending/screen ]]; then
            tr_reuse "$record_dir/pending/screen" "$path.screen" || return 1
            if [[ -f $record_dir/pending/command ]]; then
                tr_reuse "$record_dir/pending/command" "$path.command" || return 1
            fi
            # Once resolved, the live screen must be captured, even if the
            # output count happens to equal the value seen during the prompt.
            signature=pending:$signature
            reused=$((reused + 1))
        else
            old_signature=
            if [[ -n $previous && -r $previous/panes/$key.signature ]]; then
                IFS= read -r old_signature < "$previous/panes/$key.signature" || :
            fi
            if [[ $signature == "$old_signature" && -f $previous/panes/$key.screen && ${TR_FIELDS[3]} != :* ]]; then
                tr_reuse "$previous/panes/$key.screen" "$path.screen" || return 1
                reused=$((reused + 1))
            else
                tr_tmux capture-pane -p -S - -t "$pane" > "$path.screen" || return 1
                captured=$((captured + 1))
            fi
            if tmux_restore_read_active_command "$record_dir" "${TR_FIELDS[5]}" "${TR_FIELDS[6]}"; then
                # Normalized, length-safe fields, never sourced as shell code.
                printf '1\0%s\0%s\0%s\0%s\0done.1\0' "$_tmux_restore_latest_cwd" \
                    "$tmux_restore_command_shell" "$tmux_restore_command_time" "$tmux_restore_command_text" \
                    > "$path.command" || return 1
            elif tmux_restore_application_process "${TR_FIELDS[5]}"; then
                printf '%s' "${TR_FIELDS[5]}" > "$path.process" || return 1
            fi
        fi
        printf '%s\n' "$signature" > "$path.signature" || return 1
    done < "$stage/panes.meta"
    (( captured + reused > 0 )) || { tr_error 'No panes to save.'; return 1; }
    printf '%s %s\n' "$captured" "$reused" > "$stage/stats"
}

tr_prune() (
    local keep=$1 latest=$2 id count=0
    cd -- "$TR_STATE/snapshots" || return 1
    # All directory names are generated by us. Keep the committed pointer
    # even if multiple saves have the same filesystem timestamp.
    for id in $(ls -dt -- snap-* 2>/dev/null); do
        [[ $id =~ ^snap-[0-9]+-[0-9]+-[0-9]+$ && -d $id && $id != "$latest" ]] || continue
        count=$((count + 1))
        if (( count >= keep )); then rm -rf -- "$id"; fi
    done
)

tr_prune_live_records() {
    local snapshot=$1 directory id pid
    for directory in "$TR_STATE/commands/$TR_SERVER/"pane-*; do
        id=${directory##*/pane-}
        [[ -d $directory ]] && tr_uint "$id" && [[ ! -f $snapshot/panes/$id.screen ]] || continue
        # A new pane may have appeared after the snapshot was checked.
        if [[ $(tr_tmux display-message -p -t "%$id" '#{pane_id}' 2>/dev/null) != "%$id" ]]; then
            rm -rf -- "$directory"
        fi
    done
    for directory in "$TR_STATE/commands/"*-*; do
        id=${directory##*/}
        [[ -d $directory && $id != "$TR_SERVER" && $id =~ ^[0-9]+-[0-9]+$ ]] || continue
        pid=${id#*-}
        if tr_uint "$pid" && (( pid > 1 )) && ! kill -0 "$pid" 2>/dev/null; then
            rm -rf -- "$directory"
        fi
    done
}

tr_snapshot() (
    local stage= pointer= previous= epoch id keep active
    trap '[[ -z $stage ]] || rm -rf -- "$stage"; [[ -z $pointer ]] || rm -f -- "$pointer"' EXIT
    trap 'exit 130' INT TERM HUP
    keep=$(tr_option @tmux-restore-retain 10) || return 1
    if ! tr_uint "$keep" || (( keep < 1 )); then tr_error 'Snapshot retention must be a positive number.'; return 1; fi
    if ! tr_tmux has-session 2>/dev/null; then tr_error 'There are no tmux sessions to save.'; return 1; fi
    previous=$(tr_latest) || previous=
    stage=$(mktemp -d "$TR_STATE/snapshots/.staging.XXXXXXXX") || return 1
    mkdir -- "$stage/panes" || return 1
    tr_snapshot_metadata "$stage" && tr_save_panes "$stage" "$previous" || return 1
    # Refuse a mixed snapshot when a structural edit lands during capture.
    # Ignore moving focus, pane output and cwd while collecting this check.
    tr_check_structure "$stage" || return 1
    epoch=$(date +%s) || return 1
    active=$(tr_tmux display-message -p '#{session_id}') || active=
    printf '%s\n' 2 "$epoch" "$TR_SERVER" "$active" > "$stage/meta" || return 1
    id=snap-$epoch-$$-$RANDOM
    [[ ! -e $TR_STATE/snapshots/$id ]] || return 1
    mv -- "$stage" "$TR_STATE/snapshots/$id" || return 1
    stage=
    pointer=$(mktemp "$TR_STATE/.last.XXXXXXXX") || return 1
    printf '%s\n' "$id" > "$pointer" && mv -f -- "$pointer" "$TR_STATE/last" || return 1
    pointer=
    tr_tmux set-option -g @tmux-restore-last-save "$epoch" >/dev/null 2>&1 || :
    tr_prune "$keep" "$id" || :
    tr_prune_live_records "$TR_STATE/snapshots/$id" || :
)

tr_check_structure() {
    # Compare topology by IDs and indices. Tmux can zoom, resize or change
    # active panes while copying text without invalidating the original layout.
    local stage=$1 row d=$TR_FIELD expected= current
    while IFS= read -r -d "$TR_ROW" row; do
        tr_fields "$row" 8 && tr_session_id "${TR_FIELDS[0]}" && tr_window_id "${TR_FIELDS[1]}" &&
            tr_uint "${TR_FIELDS[2]}" && tr_uint "${TR_FIELDS[3]}" && tr_uint "${TR_FIELDS[4]}" &&
            tr_uint "${TR_FIELDS[5]}" && [[ ${TR_FIELDS[7]} == \{* ]] || {
            tr_error 'Invalid window metadata.'; return 1;
        }
        expected+=${TR_FIELDS[0]}$d${TR_FIELDS[1]}$d${TR_FIELDS[2]}$'\n'
    done < "$stage/windows"
    current=$(tr_tmux list-windows -a -F "#{session_id}${d}#{window_id}${d}#{window_index}") || return 1
    [[ ${expected%$'\n'} == "$current" ]] || { tr_error 'Window order changed during capture. Try again.'; return 1; }
    expected=
    while IFS= read -r -d "$TR_ROW" row; do
        tr_fields "$row" 7 || return 1
        expected+=${TR_FIELDS[0]}$d${TR_FIELDS[1]}$d${TR_FIELDS[2]}$'\n'
    done < "$stage/panes.meta"
    current=$(tr_tmux list-panes -a -F "#{window_id}${d}#{pane_id}${d}#{pane_index}") || return 1
    [[ ${expected%$'\n'} == "$current" ]] || { tr_error 'Panes changed during capture. Try again.'; return 1; }
}
